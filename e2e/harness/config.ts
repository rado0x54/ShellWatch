/**
 * Generates the `config.yaml` the server under test boots with (#244). Only the
 * documented YAML surface is used (see config.sample.yaml) — nothing is imported
 * from src/config.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { stringify as toYaml } from "yaml";
import {
  HYDRA_ADMIN_URL,
  HYDRA_PUBLIC_URL,
  RP_ID,
  SERVER_PORT,
  SERVER_URL,
  SPA_CLIENT_ID,
} from "./env.js";
import type { PasskeyIdentity } from "./identity.js";

export interface SeedEndpointSpec {
  label: string;
  /** `[user@]host[:port]` */
  address: string;
  agentForward?: boolean;
  description?: string;
}

export interface ServerConfigOptions {
  keyDirectory: string;
  adminPasskeys?: PasskeyIdentity[];
  seedEndpoints?: SeedEndpointSpec[];
  /** Enable `POST /api/auth/register` for additional accounts (cross-account scenarios). */
  selfRegistrationEnabled?: boolean;
  /** Mount `/agent-proxy` and allow the `agent` DCR scope. Default true. */
  agentProxyEnabled?: boolean;
  sessions?: { idleTimeoutMinutes?: number; cleanupIntervalSeconds?: number };
  /** Bearer-introspection cache TTL. Default 0 so revocations are observable immediately. */
  introspectionCacheTtlMs?: number;
}

export function writeServerConfig(dir: string, opts: ServerConfigOptions): string {
  const config = {
    server: { port: SERVER_PORT, externalUrl: SERVER_URL },
    keyDirectory: opts.keyDirectory,
    seedAdminPasskeys: (opts.adminPasskeys ?? []).map((pk) => ({
      credentialId: pk.credentialId,
      publicKeyHex: pk.cosePublicKeyHex,
      counter: 0,
      transports: ["internal"],
      label: pk.label,
    })),
    seedAdminEndpoints: (opts.seedEndpoints ?? []).map((ep) => ({
      label: ep.label,
      address: ep.address,
      ...(ep.agentForward !== undefined && { agentForward: ep.agentForward }),
      ...(ep.description !== undefined && { description: ep.description }),
    })),
    security: {
      rpId: RP_ID,
      trustedWebauthnOrigins: [SERVER_URL],
      selfRegistrationEnabled: opts.selfRegistrationEnabled ?? false,
      allowedNetworks: ["127.0.0.1/32", "::1/128", "::ffff:127.0.0.1/128"],
    },
    notifications: { mcp: { debounceMs: 50 } },
    agentSocket: { proxyEnabled: opts.agentProxyEnabled ?? true },
    ...(opts.sessions && { sessions: opts.sessions }),
    hydra: {
      publicUrl: HYDRA_PUBLIC_URL,
      adminUrl: HYDRA_ADMIN_URL,
      spa: { clientId: SPA_CLIENT_ID },
      introspectionCacheTtlMs: opts.introspectionCacheTtlMs ?? 0,
    },
  };
  const path = join(dir, "config.yaml");
  writeFileSync(path, `# generated by e2e/harness/config.ts\n${toYaml(config)}`);
  return path;
}
