# Append the LICENSE text of every Go module referenced by the server's go.sum
# to THIRD_PARTY_LICENSES (scripts/bundle-licenses.mjs writes the client-bundle
# half first; `pnpm licenses:bundle` runs both). Same approach as
# agent-client/scripts/bundle-licenses.sh: union over go.sum so the one bundle
# covers every target the binary is built for.
set -euo pipefail

cd "$(dirname "$0")/.."

if ! command -v jq >/dev/null 2>&1; then
  echo "error: jq is required" >&2
  exit 1
fi

OUT="THIRD_PARTY_LICENSES"
[ -f "$OUT" ] || : > "$OUT"

go mod download

{
  printf '\n\n# Server — Go module license notices\n\n'
  printf 'Aggregated license texts of every Go module referenced in `go.sum` (the `shellwatch` server binary). Generated by `scripts/bundle-go-licenses.sh` at %s.\n\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  printf -- '---\n\n'

  go list -m -json all \
    | jq -r 'select(.Main != true and .Dir != null) | "\(.Path)\t\(.Version)\t\(.Dir)"' \
    | sort \
    | while IFS=$'\t' read -r path version dir; do
        printf '## %s@%s\n\n' "$path" "$version"
        files=$(find "$dir" -maxdepth 1 -type f \( \
          -iname 'LICENSE*' -o -iname 'COPYING*' -o \
          -iname 'LICENCE*' -o -iname 'NOTICE*' \
        \) | sort || true)
        if [ -z "$files" ]; then
          printf '_(No LICENSE file shipped with this module — license declared in module metadata only)_\n\n'
        else
          count=$(printf '%s\n' "$files" | wc -l | tr -d ' ')
          while IFS= read -r f; do
            if [ "$count" -gt 1 ]; then
              printf '### %s\n\n' "$(basename "$f")"
            fi
            printf '```\n'
            cat "$f"
            printf '\n```\n\n'
          done <<< "$files"
        fi
        printf -- '---\n\n'
      done
} >> "$OUT"

echo "Appended Go module licenses to $OUT ($(wc -l < "$OUT") lines)"
